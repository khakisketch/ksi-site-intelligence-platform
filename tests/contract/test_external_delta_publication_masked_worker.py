def _write_geotiffs(tmp_path: Path) -> tuple[Path, Path, Path]:
    """Actual synthetic DSM pair (compound CRS float64) plus a uint8 mask."""
    transform = from_origin(ORIGIN_X, ORIGIN_Y, 1.0, 1.0)
    baseline_values = np.full((4, 4), 100.0)
    diff = np.zeros((4, 4), dtype=np.float64)
    diff[0, 1] = 1.0
    diff[1, 0] = 1.0
    diff[1, 1] = 1.0
    diff[2, 2] = -2.0
    current_values = baseline_values + diff
    mask = np.zeros((4, 4), dtype=np.uint8)
    mask[0, 1] = 1
    baseline_path = tmp_path / "baseline.tif"
    current_path = tmp_path / "current.tif"
    mask_path = tmp_path / "mask.tif"
    with rasterio.open(
        baseline_path,
        "w",
        driver="GTiff",
        height=4,
        width=4,
        count=1,
        dtype="float64",
        crs=COMPOUND_CRS,
        transform=transform,
    ) as dataset:
        dataset.write(baseline_values, 1)
    with rasterio.open(
        current_path,
        "w",
        driver="GTiff",
        height=4,
        width=4,
        count=1,
        dtype="float64",
        crs=COMPOUND_CRS,
        transform=transform,
    ) as dataset:
        dataset.write(current_values, 1)
    with rasterio.open(
        mask_path,
        "w",
        driver="GTiff",
        height=4,
        width=4,
        count=1,
        dtype="uint8",
        crs="EPSG:5186",
        transform=transform,
    ) as dataset:
        dataset.write(mask, 1)
    return baseline_path, current_path, mask_path


