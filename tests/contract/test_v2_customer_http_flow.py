def _dsm(values: list[list[float]]) -> bytes:
    transform = from_origin(_ORIGIN_X, _ORIGIN_Y, 0.1, 0.1)
    return _geotiff_bytes(np.array(values, dtype=float), transform=transform)


def _wire_datetime(value: datetime) -> str:
    return value.isoformat().replace("+00:00", "Z")


