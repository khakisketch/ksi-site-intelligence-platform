class _ScriptedDeltaAuthority:
    """Test DELTA publication authority with a scripted currency script.

    Each ``is_policy_current``/``is_runtime_current`` check consumes the
    next scripted verdict, so revocation can be timed exactly: before the
    pre-guard stream gate or between the stream and the post-guard recheck.
    Anything unscripted fails closed.
    """

    label = "synthetic-not-field"

    def __init__(self, script: list[bool]) -> None:
        self._script = list(script)
        self.calls = 0

    def _next(self) -> bool:
        self.calls += 1
        if not self._script:
            return False
        return self._script.pop(0)

    def is_policy_current(self, *, policy_digest: str, now: datetime) -> bool:
        return self._next()

    def is_runtime_current(
        self,
        *,
        now: datetime,
        worker_principal_id: str | None = None,
        publication_id: str | None = None,
        lease_generation: int | None = None,
    ) -> bool:
        return self._next()


def test_mask_bytes_denied_when_delta_authority_dies(tmp_path: Path) -> None:
    """Revoking DELTA_PUBLICATION_V1 denies mask bytes before and mid-stream.

    The masked execution authority that admitted the original calculation
    stays current throughout: the mask route is fenced by the publication
    authority instead. A dead authority yields no bytes and leaves the lease
    fence itself untouched.
    """
    from ksi_core.domains.external.quantity.external_delta_mask_inputs import (
        resolve_mask_bytes_for_lease,
    )

    now = datetime.now(UTC)
    now_box = [now]
    genuine = _genuine_masked_completed(tmp_path / "genuine-auth", now=now)
    worker = _worker()
    operator = _operator()
    lane = {
        "now_box": now_box,
        "journals": [],
        "adapter": genuine["adapter"],
        "coordinator": genuine["coordinator"],
        "record_envelope_digest": genuine["sealed"]["envelope"].canonical_digest(),
    }
    # 2 (intent) + 2 (lease) + 2 (pre-guard) True, then revocation wins.
    scripted = _ScriptedDeltaAuthority([True] * 6 + [False] * 10)
    store, _, _ = _publication_lane(
        tmp_path, lane=lane, worker_principal=worker, authority=scripted
    )
    identity = genuine["identity"]
    numeric = genuine["report"].numeric_result
    store.request_publication(
        principal=operator,
        publication_id="masked-auth-1",
        site_id="site-a",
        work_area_id="work-area-a",
        source_calculation_identity_digest=identity.canonical_digest(),
        source_numeric_result_identity_digest=numeric.canonical_digest(),
        source_coverage_witness_digest=numeric.coverage.canonical_digest(),
        lifetime_seconds=300,
    )
    lease = store.acquire_upload_lease(
        worker_principal=worker,
        publication_id="masked-auth-1",
        worker_instance_id="masked-instance-1",
        lease_acquisition_id="masked-acq-1",
        now=now_box[0],
    )
    assert lease is not None

    def _resolve(cap: int = 4_000_000) -> bytes | None:
        return resolve_mask_bytes_for_lease(
            store=store,
            material_resolver=genuine["adapter"],
            mask_manifests=genuine["ingress"],
            mask_bytes=genuine["mask_bytes_store"],
            publication_id="masked-auth-1",
            worker_principal=worker,
            worker_instance_id="masked-instance-1",
            lease_generation=1,
            max_mask_bytes=cap,
            now=now_box[0],
        )

    # Authority dies during the stream: the post-guard recheck fails closed
    # and no bytes are returned even though the pre-guard passed.
    assert _resolve() is None
    before = (tmp_path / "masked-lane-pubs.journal").read_text()
    # A byte cap below the sealed binding size denies the read outright.
    assert _resolve(cap=1) is None
    # Authority dead before the stream: the pre-guard fails closed.
    scripted._script.clear()
    assert _resolve() is None
    assert (tmp_path / "masked-lane-pubs.journal").read_text() == before
    # The fence itself is untouched: the live lease is still held.
    assert (
        store.intent_for_worker(
            "masked-auth-1", worker_principal=worker, worker_instance_id="masked-instance-1"
        )
        is not None
    )
