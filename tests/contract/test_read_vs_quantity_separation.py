def test_read_path_coupled_to_quantity_would_fail_this_pin(
    lane: SimpleNamespace, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Mutation proof: gating reads on quantitative eligibility breaks the pin.

    Simulates the forbidden coupling (a read gate consulting quantitative
    eligibility) with a test-controlled patch, observes the allowed read
    fail, then restores the genuine gate and observes the pin hold again.
    """
    real_require_scope = catalog_module.SpatialAssetCatalog._require_scope

    def coupled_require_scope(self: Any, site_id: str, work_area_id: str, principal: Any) -> None:
        real_require_scope(self, site_id, work_area_id, principal)
        raise HTTPException(status_code=403, detail="QUANTITATIVE_ELIGIBILITY_REQUIRED")

    monkeypatch.setattr(catalog_module.SpatialAssetCatalog, "_require_scope", coupled_require_scope)
    with TestClient(lane.ctx.app) as client:
        coupled = client.get(lane.catalog_root, headers=_op_headers())
        assert coupled.status_code == 403
        assert coupled.json()["detail"] == "QUANTITATIVE_ELIGIBILITY_REQUIRED"
    monkeypatch.undo()
    with TestClient(lane.ctx.app) as client:
        restored = client.get(lane.catalog_root, headers=_op_headers())
        assert restored.status_code == 200, restored.text
        assert all(item["analysisStatus"] == "NOT_EVALUATED" for item in restored.json()["assets"])


