def _metric(body: object, key: str) -> float | None:
    found: list[float] = []

    def walk(node: object) -> None:
        if isinstance(node, dict):
            for name, value in node.items():
                if name == key and isinstance(value, (int, float)):
                    found.append(float(value))
                else:
                    walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    walk(body)
    return found[0] if found else None


def _register_pair_epoch(
    customer: CustomerV2Client, harness: CustomerHttpHarness, label: str, dsm: bytes
) -> tuple[str, str]:
    name = f"c3-{label}"
    order = customer.create_work_order(name, idempotency_key=f"c3-order-{label}")
    work_order_id = order["workOrderId"]
    harness.remember_order(label, work_order_id, name)
    fetched = customer.get_work_order(work_order_id)
    assert fetched["siteId"] == "site-a"
    assert fetched["workAreaIds"] == [harness.work_area_id]
    context = customer.get_registration_context(work_order_id)
    assert context["workOrderId"] == work_order_id
    wire = _v2_wire(label=label, epoch_id=context["expectedEpochId"], dsm_bytes=dsm)
    registered = customer.register_submission_v2(work_order_id, wire)
    submission_ref = registered["submissionRef"]
    harness.remember_ref(label, submission_ref)
    grants = customer.request_upload_grants(work_order_id, submission_ref)
    assert len(grants) == 1
    customer.put_object_bytes(
        grants[0]["uploadUrl"],
        dsm,
        content_type="application/octet-stream",
        required_headers=grants[0]["requiredHeaders"],
    )
    sealed = customer.seal_revision(work_order_id, submission_ref)
    assert sealed["manifest"] is not None
    return submission_ref, grants[0]["artifactId"]


