    # -- signed manifests (test-generated keys, real verifier) ---------
    def _sign_manifests(self) -> None:
        import base64 as _base64

        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
        from ksi_event_contracts.inspector_execution_manifest import (
            InspectorExecutionManifestSignatureV1,
            InspectorExecutionManifestV1,
        )
        from ksi_processing_controller.external_inspector_catalog import (
            Ed25519InspectorManifestVerifier,
            InspectorTrustRootV1,
        )
        from ksi_processing_controller.external_measurement_protocol import (
            compiled_measurement_backend_profile_digest_v2,
            compiled_measurement_protocol_digest_v2,
        )
        from test_external_inspector_container_entrypoint import (
            _manifest as _unsigned_manifest,
        )

        key = Ed25519PrivateKey.generate()
        unsigned = _unsigned_manifest(self._envelope)

        def _sign(body: Any) -> InspectorExecutionManifestV1:
            raw_signature = key.sign(body.canonical_body_bytes())
            return InspectorExecutionManifestV1(
                body=body,
                signature=InspectorExecutionManifestSignatureV1(
                    algorithm="Ed25519",
                    key_id="c3-test-key-1",
                    digest=body.canonical_body_digest(),
                    signature=_base64.b64encode(raw_signature).decode("ascii"),
                ),
            )

        self._inspector_manifest = _sign(unsigned.body)
        measurement_body = unsigned.body.model_copy(
            update={
                "inspector_protocol_digest": compiled_measurement_protocol_digest_v2(),
                "backend_profile_digest": compiled_measurement_backend_profile_digest_v2(),
            }
        )
        self._measurement_manifest = _sign(measurement_body)
        public_bytes = (
            key.public_key().public_bytes_raw()
            if hasattr(key.public_key(), "public_bytes_raw")
            else None
        )
        if public_bytes is None:  # pragma: no cover - cryptography API shape guard
            raise AssertionError("Ed25519 raw public bytes unavailable")
        self._manifest_verifier = Ed25519InspectorManifestVerifier(
            InspectorTrustRootV1(public_keys={"c3-test-key-1": public_bytes})
        )

    def admit_inspector_launch(self, request: Any, *, manifest: Any | None = None) -> None:
        """Mandatory per-launch gate: real signature + binding + ceilings."""
        from ksi_event_contracts.inspector_execution_manifest import (
            validate_inspector_execution_binding,
            verify_inspector_execution_manifest_signature,
        )
        from ksi_processing_controller.external_geotiff_profile import (
            external_geotiff_profile_digest_v1,
        )
        from ksi_processing_controller.external_inspector_protocol import ProtocolViolation

        active = manifest if manifest is not None else self._inspector_manifest
        if not verify_inspector_execution_manifest_signature(active, self._manifest_verifier):
            raise ProtocolViolation("inspector manifest signature invalid")
        try:
            validate_inspector_execution_binding(request.policy, active)
        except ValueError as exc:
            raise ProtocolViolation(f"inspector execution binding differs: {exc}") from exc
        if request.policy.grammar_digest != external_geotiff_profile_digest_v1():
            raise ProtocolViolation("inspector grammar differs")
        envelope = request.policy.resource_envelope
        body = active.body
        if (
            envelope is None
            or envelope.resource_envelope_digest != body.resource_envelope_digest
            or request.sealed_byte_binding.observed_size_bytes
            > min(envelope.max_input_bytes, body.hard_ceilings.max_input_bytes)
        ):
            raise ProtocolViolation("inspector envelope/ceiling differs")

