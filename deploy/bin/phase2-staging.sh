#!/usr/bin/env bash
set -euo pipefail
umask 077

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_dir="$(cd -- "$script_dir/../.." && pwd)"
compose_file="$repo_dir/deploy/compose.synthetic-staging.yaml"
state_dir="$repo_dir/.dev-data/phase2-synthetic-staging"
env_file="$state_dir/staging.env"

usage() {
  echo "usage: $0 start|status|verify|stop|reset" >&2
  exit 2
}

[[ $# -eq 1 ]] || usage
action="$1"

prepare_env() {
  local host
  host="$(tailscale status --json | jq -r '.Self.DNSName // ""' | sed 's/\.$//')"
  [[ "$host" == *.ts.net ]] || { echo "Tailnet MagicDNS host is unavailable" >&2; exit 1; }
  uv run --locked python "$repo_dir/deploy/synthetic-staging/prepare_env.py" \
    --output "$env_file" --host "$host" >/dev/null
}

load_env() {
  prepare_env
  set -a
  # Generated by prepare_env.py with newline-free values and owner-only mode.
  # shellcheck disable=SC1090
  source "$env_file"
  set +a
}

compose() {
  docker compose --env-file "$env_file" -f "$compose_file" "$@"
}

serve_on() {
  local port="$1"
  tailscale serve --https="$port" --bg --yes "http://127.0.0.1:${port}" >/dev/null
}

serve_off() {
  local port="$1"
  tailscale serve --https="$port" off >/dev/null 2>&1 || true
}

wait_for() {
  local url="$1"
  local label="$2"
  for _ in $(seq 1 80); do
    if curl --fail --silent --show-error --max-time 2 "$url" >/dev/null 2>&1; then
      return 0
    fi
    sleep 0.5
  done
  echo "$label did not become ready: $url" >&2
  return 1
}

start() {
  load_env
  # init-state/identity/synthetic-copilot share the exact Core image tag.
  # Build it once to avoid concurrent writers racing on the same local tag.
  compose build core dashboard
  compose up -d init-state minio bucket-init synthetic-copilot identity
  wait_for "http://127.0.0.1:${KSI_STAGING_IDENTITY_PORT}/healthz" "identity"
  serve_on "$KSI_STAGING_IDENTITY_PORT"
  compose --profile seed run --rm seed
  compose up -d core dashboard
  wait_for "http://127.0.0.1:${KSI_STAGING_API_PORT}/ready" "Core"
  wait_for "http://127.0.0.1:${KSI_STAGING_APP_PORT}/api/health" "Dashboard"
  serve_on "$KSI_STAGING_API_PORT"
  serve_on "$KSI_STAGING_OBJECTS_PORT"
  serve_on "$KSI_STAGING_APP_PORT"
  "$script_dir/smoke-synthetic-staging.sh" \
    "$KSI_STAGING_HOST" "$KSI_STAGING_APP_PORT" "$KSI_STAGING_IDENTITY_PORT" \
    "$KSI_STAGING_API_PORT" "$KSI_STAGING_OBJECTS_PORT"
  echo "Phase 2 Console: https://${KSI_STAGING_HOST}:${KSI_STAGING_APP_PORT}/login"
}

status() {
  load_env
  compose ps
  tailscale serve status --json | jq --argjson app "$KSI_STAGING_APP_PORT" \
    --argjson identity "$KSI_STAGING_IDENTITY_PORT" \
    --argjson api "$KSI_STAGING_API_PORT" \
    --argjson objects "$KSI_STAGING_OBJECTS_PORT" \
    '.TCP | with_entries(select((.key|tonumber) == $app or (.key|tonumber) == $identity or (.key|tonumber) == $api or (.key|tonumber) == $objects))'
}

verify() {
  load_env
  "$script_dir/smoke-synthetic-staging.sh" \
    "$KSI_STAGING_HOST" "$KSI_STAGING_APP_PORT" "$KSI_STAGING_IDENTITY_PORT" \
    "$KSI_STAGING_API_PORT" "$KSI_STAGING_OBJECTS_PORT"
  (
    local keys_dir backup_root bundle
    keys_dir="$(mktemp -d)"
    backup_root="$state_dir/backups"
    cleanup_verify() {
      set +e
      rm -rf -- "$keys_dir"
      compose up -d core dashboard >/dev/null
    }
    trap cleanup_verify EXIT
    docker run --rm -v ksi-phase2-staging-signing:/source:ro -v "$keys_dir":/target \
      alpine:3.22@sha256:14358309a308569c32bdc37e2e0e9694be33a9d99e68afb0f5ff33cc1f695dce sh -c \
      "cp -a /source/. /target/ && chown -R $(id -u):$(id -g) /target"
    compose stop dashboard core >/dev/null
    bundle="$(
      KSI_BACKUP_DATA_VOLUME=ksi-phase2-staging-data \
      KSI_BACKUP_OBJECTS_VOLUME=ksi-phase2-staging-objects \
      KSI_BACKUP_SIGNING_KEYS_DIR="$keys_dir" \
        "$script_dir/backup-vm.sh" "$backup_root"
    )"
    "$script_dir/restore-check-vm.sh" "$bundle"
    compose up -d core dashboard >/dev/null
    wait_for "http://127.0.0.1:${KSI_STAGING_APP_PORT}/api/health" \
      "Dashboard after restore drill"
    echo "Phase 2 backup bundle: $bundle"
  )
}

stop() {
  load_env
  for port in "$KSI_STAGING_APP_PORT" "$KSI_STAGING_IDENTITY_PORT" \
    "$KSI_STAGING_API_PORT" "$KSI_STAGING_OBJECTS_PORT"; do
    serve_off "$port"
  done
  compose down
}

reset() {
  load_env
  for port in "$KSI_STAGING_APP_PORT" "$KSI_STAGING_IDENTITY_PORT" \
    "$KSI_STAGING_API_PORT" "$KSI_STAGING_OBJECTS_PORT"; do
    serve_off "$port"
  done
  compose down --volumes --remove-orphans
  echo "Synthetic staging containers and named volumes removed; runtime env/backups remain in $state_dir"
}

case "$action" in
  start) start ;;
  status) status ;;
  verify) verify ;;
  stop) stop ;;
  reset) reset ;;
  *) usage ;;
esac
