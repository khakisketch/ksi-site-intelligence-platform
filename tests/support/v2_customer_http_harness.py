    def inspect_subjects(self, pairs: list[SealedPair]) -> Any:
        """Worker-side inspection through the real lane and real byte parser.

        Every UDS launch passes the mandatory signature/binding/ceiling gate
        before the entrypoint reads the sealed bytes. The measured outcomes
        come from parsing the actual customer-uploaded GeoTIFF bytes; they are
        still software-only execution (no container containment proof) and the
        generated bytes never prove field truth.
        """
        from ksi_processing_controller.external_validation_core_client import (
            ExternalValidationCoreClient,
        )
        from ksi_processing_controller.external_validation_runner import TurnOutcome
        from test_external_analysis_real_inspection_integration import _RealDsmInspectorUds
        from test_external_analysis_real_inspection_lane_integration import _inspection_lane

        assert self._policy is not None
        socket_path = _socket_dir() / f"c3-inspect-{uuid4().hex}.sock"
        inspector_root = self._path / "real-inspector-root"
        inspector_root.mkdir(mode=0o700, exist_ok=True)
        private_root = self._path / "inspection-lane-private"
        if private_root.exists():
            import shutil

            shutil.rmtree(private_root)
        store = self._app.state.external_artifact_inspection_store
        assert self._policy.resource_envelope is not None
        lease_spacing = float(self._policy.resource_envelope.lease_duration_seconds) + 1.0
        last_claim_at = 0.0
        with _RealDsmInspectorUds(
            path=socket_path,
            manifest=self._inspector_manifest,
            root=inspector_root,
            admit=self.admit_inspector_launch,
        ) as inspector:
            self._last_inspector = inspector
            core = ExternalValidationCoreClient(
                base_url=self.core_origin, bearer_token=self._validation_worker_token
            )
            lane = _inspection_lane(
                SimpleNamespace(_inspection_policy=self._policy),
                core=core,
                object_origin=self.object_origin,
                socket_path=socket_path,
                private_root=private_root,
                worker_instance_id=str(uuid4()),
            )
            try:
                for pair in pairs:
                    now = max(datetime.now(UTC).replace(microsecond=0), self._now)
                    issued = store.issue_after_seal(pair.subject, now=now)
                    assert issued.request is not None
                    assert issued.verdict.value in {"ISSUED", "IDEMPOTENT"}
                    # The pending queue is not subject-ordered: keep claiming
                    # and executing in queue order until this subject reports.
                    for _turn in range(len(pairs) + 2):
                        if store.public_snapshot(pair.subject).report is not None:
                            break
                        deadline = time.monotonic() + 60
                        request_id = lane.poll(deadline_monotonic=deadline)
                        assert request_id is not None
                        # Core leases stay live server-side for the full lease
                        # duration (client release drops only local caches), so
                        # the worker waits for tenant-concurrency capacity
                        # instead of tripping the production ceiling.
                        wait = lease_spacing - (time.monotonic() - last_claim_at)
                        if wait > 0:
                            time.sleep(wait)
                        lease = lane.claim(
                            request_id,
                            str(uuid4()),
                            deadline_monotonic=time.monotonic() + 60,
                        )
                        last_claim_at = time.monotonic()
                        assert lease is not None
                        try:
                            assert (
                                lane.execute(
                                    lease,
                                    deadline_monotonic=time.monotonic() + 60,
                                    stop=Event(),
                                )
                                is TurnOutcome.COMPLETED
                            )
                        finally:
                            lane.release(lease)
                    snapshot = store.public_snapshot(pair.subject)
                    assert snapshot.report is not None
            finally:
                lane.close()
        assert inspector.rejected == []
        assert len(inspector.admitted) >= len(pairs)
        assert len(inspector.measured) >= len(pairs)
        return inspector

