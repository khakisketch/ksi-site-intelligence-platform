def _grant_bounds(measurements: Any, *, left_half: bool) -> tuple[float, float, float, float]:
    transform = measurements.transform
    width, height = measurements.width, measurements.height
    x0, dx, y0, dy = transform[2], transform[0], transform[5], transform[4]
    # Generated 2x2 DSM at the fixed origin: x grows east, y grows down.
    return (
        (x0, y0 + dy * height, x0 + dx * width / 2, y0)
        if left_half
        else (x0, y0 + dy * height, x0 + dx * width, y0)
    )


def test_spatial_read_works_under_grant_and_prepare_without_capability_is_denied(
    lane: SimpleNamespace,
) -> None:
    """Reads serve under the grant; uncovered PREPARE is refused, never faked.

    Denials are layered by design: the HTTP issue selector answers 403
    GRANT_REQUIRED when no grant covers a PREPARE request (it never names a
    reason that would enumerate rights), while the exact capability /
    containment reason surfaces at the grant check itself --
    PERMISSION_DENIED for a missing PREPARE capability and
    OUTPUT_OUTSIDE_GRANT for a containment breach. Revoking the grant flips
    the issued read to a typed ACCESS_REVOKED instead of serving the earlier
    read as if rights persisted.
    """
    from ksi_event_contracts.spatial_data import SpatialDataPurposeV1
    from ksi_geo_spatial.external_native_window_geometry import plan_external_native_window

    wiring = lane.wiring
    measurements = lane.baseline_source.inspection.measurements
    assert measurements is not None
    left = _grant_bounds(measurements, left_half=True)
    grant = make_grant(
        grant_id="read-vs-quantity-region-grant",
        organization_id="org-a",
        beneficiary_principal_id="platform-flow-operator",
        asset_ref=lane.baseline_source.asset_ref,
        site_id=lane.ctx.site_id,
        work_area_id=lane.ctx.work_area_id,
        allowed_bounds=left,
        observed_crs_digest=measurements.observed_crs_digest,
        policy_digest=wiring.config.policy.policy_digest,
        valid_from=lane.now - timedelta(minutes=1),
        valid_until=lane.now + timedelta(hours=1),
    )
    wiring.grants.provision(grant)
    x0, y_bottom, x_mid, _ = left
    inside = [x0, y_bottom + 0.05, x0 + 0.05, y_bottom + 0.15]
    outside = [x_mid + 0.05, y_bottom + 0.05, x_mid + 0.1, y_bottom + 0.15]

    def body(bounds: list[float], purpose: str = "GENERAL_DATA_USE") -> dict[str, Any]:
        return {
            "assetRef": lane.baseline_source.asset_ref,
            "requestedBounds": bounds,
            "observedCrsDigest": measurements.observed_crs_digest,
            "resolutionMode": "NATIVE",
            "purpose": purpose,
        }

    def check(
        source: Any,
        measurements: Any,
        bounds: tuple[float, float, float, float],
        grant_id: str,
        operation: str,
    ) -> str:
        geometry = plan_external_native_window(
            requested_bounds=bounds,
            measurements=measurements,
            requested_crs_digest=measurements.observed_crs_digest,
        )
        try:
            wiring.authorizer.require_current(
                grant_id=grant_id,
                revision=1,
                source=source,
                principal=lane.operator,
                purpose=SpatialDataPurposeV1.GENERAL_DATA_USE,
                requested_bounds=bounds,
                geometry=geometry,
                operation=operation,
                policy=wiring.config.policy,
                now=lane.now,
            )
        except Exception as exc:  # noqa: BLE001 -- the denial reason is the assertion
            assert getattr(exc, "reason", None) is not None
            return str(exc.reason)  # type: ignore[attr-defined]
        return "GRANTED"

    with TestClient(lane.ctx.app) as client:
        issued = client.post(
            lane.spatial_root,
            headers={**_op_headers(), "Idempotency-Key": "rq-issue"},
            json=body(inside),
        )
        assert issued.status_code == 201, issued.text
        view = issued.json()
        assert view["executionState"] == "QUEUED"
        assert view["availability"] == "NOT_READY"
        assert view["receipt"] is None
        for forbidden in ("objectKey", "capability", "policy"):
            assert forbidden not in issued.text
        fetched = client.get(lane.spatial_root + "/" + view["jobId"], headers=_op_headers())
        assert fetched.status_code == 200, fetched.text
        assert fetched.json() == view
        # No grant covers a PREPARE request outside the granted containment.
        refused_bounds = client.post(
            lane.spatial_root,
            headers={**_op_headers(), "Idempotency-Key": "rq-bounds"},
            json=body(outside),
        )
        assert refused_bounds.status_code == 403, refused_bounds.text
        assert refused_bounds.json()["reason"] == "GRANT_REQUIRED"
        assert (
            check(lane.baseline_source, measurements, tuple(outside), grant.grant_id, "PREPARE")
            == "OUTPUT_OUTSIDE_GRANT"
        )
        # Capability: a READ-only grant cannot back PREPARE-scoped issuance.
        current_measurements = lane.current_source.inspection.measurements
        assert current_measurements is not None
        read_only = make_grant(
            grant_id="read-vs-quantity-read-only-grant",
            organization_id="org-a",
            beneficiary_principal_id="platform-flow-operator",
            asset_ref=lane.current_source.asset_ref,
            site_id=lane.ctx.site_id,
            work_area_id=lane.current_source.work_area_id,
            allowed_bounds=_grant_bounds(current_measurements, left_half=False),
            observed_crs_digest=current_measurements.observed_crs_digest,
            operations=("READ",),
            policy_digest=wiring.config.policy.policy_digest,
            valid_from=lane.now - timedelta(minutes=1),
            valid_until=lane.now + timedelta(hours=1),
        )
        wiring.grants.provision(read_only)
        refused_capability = client.post(
            lane.spatial_root,
            headers={**_op_headers(), "Idempotency-Key": "rq-cap"},
            json={
                "assetRef": lane.current_source.asset_ref,
                "requestedBounds": list(_grant_bounds(current_measurements, left_half=True)),
                "observedCrsDigest": current_measurements.observed_crs_digest,
                "resolutionMode": "NATIVE",
                "purpose": "GENERAL_DATA_USE",
            },
        )
        assert refused_capability.status_code == 403, refused_capability.text
        assert refused_capability.json()["reason"] == "GRANT_REQUIRED"
        current_left = _grant_bounds(current_measurements, left_half=True)
        assert (
            check(
                lane.current_source,
                current_measurements,
                current_left,
                read_only.grant_id,
                "PREPARE",
            )
            == "PERMISSION_DENIED"
        )
        # Currentness: revoking the grant flips the issued view to a typed
        # denial instead of serving the earlier read as if rights persisted.
        wiring.grants.revoke(
            make_revocation(
                grant_id=grant.grant_id,
                revision=grant.revision,
                organization_id=grant.organization_id,
                grant_digest=grant.grant_digest,
                revoked_at=lane.now,
            )
        )
        revoked = client.get(lane.spatial_root + "/" + view["jobId"], headers=_op_headers())
        assert revoked.status_code == 200, revoked.text
        assert revoked.json()["availability"] == "ACCESS_REVOKED"
        assert revoked.json()["reason"] == "ACCESS_REVOKED"


def test_failed_evaluation_suppresses_numbers_but_not_allowed_reads(
    lane: SimpleNamespace,
) -> None:
    """A failed evaluation for the same bytes suppresses only the number."""
    later = datetime.now(UTC).replace(microsecond=0)
    _validate_evidence(
        lane.ctx.app,
        revision=lane.current_revision,
        subject=lane.current_subject,
        policy=lane.policy,
        context_authority=lane.ctx.context_authority,
        now=later,
        storage=lane.ctx.storage,
        label="read-vs-quantity-late-rejected",
        checkpoint_count=1,
    )
    with TestClient(lane.ctx.app) as client:
        second = client.post(
            f"/v1/sites/{lane.ctx.site_id}/work-areas/{lane.ctx.work_area_id}/analyses",
            headers={**_op_headers(), "Idempotency-Key": _REMEDIATION_IDEMPOTENCY},
            json=lane.request,
        )
        assert second.status_code == 202, second.text
        assert second.json()["suitabilityState"] == "REMEDIATION_REQUIRED"
        assert second.json()["executionState"] == "NOT_STARTED"
        assert second.json()["result"] is None
        assert {item["code"] for item in second.json()["blockers"]} == {
            "CHECKPOINT_COUNT_OUT_OF_RANGE",
            "CHECKPOINT_EVIDENCE_ABSENT",
        }
        for forbidden in ("cutM3", "fillM3", "netM3"):
            assert forbidden not in second.text
        remediation_id = second.json()["analysisId"]
        assert remediation_id != lane.analysis_id
        for suffix in ("", "/result", "/evidence"):
            response = client.get(
                f"/v1/sites/{lane.ctx.site_id}/analyses/{remediation_id}{suffix}",
                headers=_op_headers(),
            )
            assert response.status_code == 200, response.text
            assert response.json()["result"] is None
        evidence = client.get(
            f"/v1/sites/{lane.ctx.site_id}/analyses/{remediation_id}/evidence",
            headers=_op_headers(),
        ).json()
        evaluations = {item["epoch"]: item for item in evidence["evaluations"]}
        assert evaluations["CURRENT"]["outcome"] == "FAIL"
        assert evaluations["CURRENT"]["reasonCodes"] == ["CHECKPOINT_COUNT_OUT_OF_RANGE"]
        assert evaluations["CURRENT"]["revision"] == 2
        assert evaluations["BASELINE"]["outcome"] == "UNASSESSED"
        assert evaluations["BASELINE"]["revision"] == 1
        pending = client.get("/v1/internal/analysis-jobs", headers=_WORKER_HEADERS)
        assert pending.status_code == 200, pending.text
        assert remediation_id not in {item.get("analysisId") for item in pending.json()["items"]}
        claim = client.post(
            f"/v1/internal/analysis-jobs/{remediation_id}:lease",
            headers=_WORKER_HEADERS,
            json={
                "workerInstanceId": "read-vs-quantity-worker",
                "leaseAcquisitionId": "read-vs-quantity-lease",
            },
        )
        assert claim.status_code == 404, claim.text
        # The earlier provisional record stays tenant-retrievable with no number.
