"""Read access never implies quantitative suitability (product-boundary pin).

Pinned property (Constitution §제품 정체성 3-layer verdict, PRD §1.1.2,
ADR-KSI-038 D2/D4, ADR-KSI-037 D3/D5): a data artifact that is NOT
quantitatively eligible must stay readable through its allowed read paths,
and read access must never imply quantitative suitability. The three verdict
layers stay distinct:

- asset/observation validity (sealed bytes, measured geometry),
- purpose-specific suitability (read vs prepare, display, analysis), and
- reproducibility of a computed result (which never exists here).

Method: ONE mounted platform app over ONE generated/sealed DSM pair with NO
independent measurement checkpoint. The DSM bytes are generated locally, the
inspection reports come from the real inspector lane, and every assertion
below traverses the real Core stores and routers (no mocks of the behaviour
under test). What is synthetic is only measurement *input* framing shared
with the neighbouring fixtures (explicit local authority, generated bytes);
no customer data, no network beyond loopback, no product-code change.

Evidence boundary: this is local software proof only. It is NOT customer,
field, or production acceptance, and it proves nothing about Terra export
compatibility, absolute accuracy, settlement, or any approval.

Test map:
1. catalog list/detail read succeeds and reports analysisStatus
   NOT_EVALUATED (never a quantitative claim).
2. revision inspection-fact read succeeds under SITES_READ for the same
   bytes; the display fact is an explicit typed absence, and a missing
   receipt download is a non-disclosing 404 -- never fabricated bytes.
3. the V2 quantitative path admits the pair as ADMIT_PROVISIONAL
   (suitability PROVISIONAL_ACCURACY_UNVERIFIED, execution QUEUED) with no
   numeric result anywhere in the response.
4. the spatial-data lane reads under its grant, while PREPARE without the
   matching grant capability/containment, and reads after revocation, return
   typed denials -- never fabricated success.
5. injecting a failed checkpoint evaluation for the same bytes flips new
   work to REMEDIATION_REQUIRED with numeric retrieval suppressed, while
   (1) and (2) still succeed.
6. static schema pin + a controlled mutation proof so the pin cannot rot.
"""

