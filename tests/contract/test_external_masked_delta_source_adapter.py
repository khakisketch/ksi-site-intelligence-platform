"""V3 publication sources are genuine masked results, never completed V2 numerics.

Generated bytes and temporary signatures prove local binding/currentness only.
The fixture's incumbent DSM inspection authority remains explicitly test-scoped.
"""

from __future__ import annotations

import json
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import pytest
from ksi_core.domains.external.quantity.external_masked_delta_source_adapter import (
    CoreMaskedDeltaSourceAdapter,
)
from ksi_core.foundation.currentness import ExternalAuthorityCurrentnessCoordinator
from test_external_mask_input_genuine_adapters import NOW, _run_genuine_chain


@pytest.fixture
def graph(tmp_path: Path) -> Iterator[dict[str, Any]]:
    result = _run_genuine_chain(tmp_path, current_nan_at=(0, 1))
    yield result
    result["byte_store"].close()
    for key in (
        "reconstruction",
        "inspections",
        "work_areas",
        "assessments",
        "evidence",
        "validations",
        "policy_registry",
        "ingress",
        "byte_store",
        "calc",
    ):
        result[key]._journal.close()


def _args(result: dict[str, Any]) -> dict[str, Any]:
    identity, numeric = result["identity"], result["numeric"]
    return {
        "organization_id": identity.organization_id,
        "site_id": identity.site_id,
        "work_area_id": identity.work_area_id,
        "source_calculation_identity_digest": identity.canonical_digest(),
        "source_numeric_result_identity_digest": numeric.canonical_digest(),
        "source_coverage_witness_digest": numeric.coverage.canonical_digest(),
        "now": NOW,
    }


def test_masked_source_resolves_without_any_completed_v2_numeric_and_keeps_unknown_impact(
    graph: dict[str, Any],
) -> None:
    adapter = CoreMaskedDeltaSourceAdapter(
        calculations=graph["calc"], coordinator=graph["coordinator"]
    )
    args = _args(graph)
    source = adapter.resolve_current_source(**args)
    material = adapter.resolve_current_material(**args)
    assert source is not None and material is not None
    assert source.source_contract_version == "external-masked-volume-calculation-identity.v3"
    assert (
        source.source_calculation_identity_digest
        != graph["identity"].source_calculation_identity.canonical_digest()
    )
    assert material.masked_calculation_identity == graph["identity"]
    assert material.report == graph["report"]
    assert not material.report.numeric_result.impact.unmasked_impact_known
    assert material.report.numeric_result.impact.excluded_fill_m3 is None
    assert graph["full_zone_finite_fraction"] < 1.0
    assert source.grid_rows == source.grid_columns == 4
    assert source.bounds == graph["numeric"].coverage.bounds


@pytest.mark.parametrize(
    "field",
    [
        "organization_id",
        "site_id",
        "work_area_id",
        "source_calculation_identity_digest",
        "source_numeric_result_identity_digest",
        "source_coverage_witness_digest",
    ],
)
def test_masked_source_cannot_borrow_another_scope_or_result(
    graph: dict[str, Any], field: str
) -> None:
    adapter = CoreMaskedDeltaSourceAdapter(
        calculations=graph["calc"], coordinator=graph["coordinator"]
    )
    value = "sha256:" + "0" * 64 if field.endswith("digest") else "foreign"
    assert adapter.resolve_current_source(**{**_args(graph), field: value}) is None


def test_masked_source_is_no_longer_current_when_the_actual_activation_key_is_revoked(
    graph: dict[str, Any],
) -> None:
    adapter = CoreMaskedDeltaSourceAdapter(
        calculations=graph["calc"], coordinator=graph["coordinator"]
    )
    assert adapter.resolve_current_source(**_args(graph)) is not None
    registry_path = graph["activation_paths"][1]
    registry = json.loads(registry_path.read_text())
    registry["keys"][0]["status"] = "REVOKED"
    registry_path.write_text(json.dumps(registry))
    assert adapter.resolve_current_source(**_args(graph)) is None


def test_masked_source_cannot_be_mounted_with_an_unrelated_currentness_coordinator(
    graph: dict[str, Any],
) -> None:
    with pytest.raises(ValueError, match="exact common"):
        CoreMaskedDeltaSourceAdapter(
            calculations=graph["calc"], coordinator=ExternalAuthorityCurrentnessCoordinator()
        )
