def test_genuine_activation_rotation_invalidates_old_fence(tmp_path: Path) -> None:
    """Rotation (new key/activation record) must not keep the old attempt authorized.

    The old admission binds the actual verified activation record digest; after
    the operator replaces the activation files, the fenced witness fails
    closed while a fresh admission binds the new record.
    """
    out = _run_genuine_chain(tmp_path)
    evidence = out["masked_evidence"]
    calc = out["calc"]
    identity = out["identity"]
    envelope = out["envelope"]
    old_admission = calc.get_history(request_id="request-1", organization_id="org-a").admission
    # A fresh witness for the old admission still verifies before rotation.
    assert (
        evidence.prepare_witness(
            masked_calculation_identity_digest=identity.canonical_digest(),
            organization_id="org-a",
            now=NOW,
            expected_admission=old_admission,
        )
        is not None
    )
    # Operator rotates the activation (new key, new record id).
    lane_runtime = masked_execution_runtime_digest(
        out["execution_runtime"],
        out["masked_profile"].canonical_digest(),
        envelope.canonical_digest(),
        out["mask_profile"].canonical_digest(),
    )
    _mint_extension_activation(
        tmp_path / "activation-rotated",
        organization_id="org-a",
        policy_digest=out["masked_profile"].canonical_digest(),
        runtime_digest=lane_runtime,
        envelope_digest=envelope.canonical_digest(),
        worker=_designated_worker(),
        now=NOW,
    )
    import shutil as _shutil

    original_activation_bytes = (
        tmp_path / "activation" / "quantitative-extension-activation.json"
    ).read_bytes()
    for name in (
        "quantitative-extension-activation.json",
        "quantitative-extension-activation-keys.json",
        "quantitative-extension-key-1.public.pem",
    ):
        _shutil.copy(tmp_path / "activation-rotated" / name, tmp_path / "activation" / name)
    rotated_paths = (
        tmp_path / "activation" / "quantitative-extension-activation.json",
        tmp_path / "activation" / "quantitative-extension-activation-keys.json",
    )
    assert rotated_paths[0].read_bytes() != original_activation_bytes
    # The old admission no longer verifies: lease fence fails closed.
    assert (
        evidence.prepare_witness(
            masked_calculation_identity_digest=identity.canonical_digest(),
            organization_id="org-a",
            now=NOW,
            expected_admission=old_admission,
        )
        is None
    )
    assert (
        calc.acquire_lease(
            request_id="request-1",
            worker_principal=_designated_worker(),
            worker_instance_id="masked-worker-instance-9",
            lease_acquisition_id="lease-9",
            now=NOW,
        )
        is None
    )
    # A fresh admission binds the rotated record instead of the old digest.
    fresh = evidence.prepare_witness(
        masked_calculation_identity_digest=identity.canonical_digest(),
        organization_id="org-a",
        now=NOW,
    )
    assert fresh is not None
    assert fresh.admission.activation_digest != old_admission.activation_digest


