class _StrictObjectStorage:
    """Test protected storage: presigned loopback URLs for retained bytes only."""

    label = "synthetic-not-field"

    def __init__(self, origin: str, objects: dict[str, bytes]) -> None:
        self._origin = origin.rstrip("/")
        self._objects = dict(objects)

    def presigned_get(self, object_key: str, *, ttl: timedelta) -> str:
        from datetime import timedelta as _timedelta

        if object_key not in self._objects or not isinstance(ttl, _timedelta):
            raise ValueError("unknown object key")
        from urllib.parse import quote as _quote

        return self._origin + "/objects/" + _quote(object_key, safe="")

    def object_bytes(self, object_key: str) -> bytes:
        return self._objects[object_key]


def _manifest_entry(
    *, artifact_id: str, observed_sha256: str, observed_size_bytes: int, object_key: str
) -> Any:
    from ksi_event_contracts.processing_artifact import ProcessingArtifactKind

    class _Entry:
        def __init__(self) -> None:
            self.kind = ProcessingArtifactKind.DSM
