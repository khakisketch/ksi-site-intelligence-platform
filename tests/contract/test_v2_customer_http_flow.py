"""C3/C4: customer HTTP-only E2E over real loopback sockets (generated data only).

The customer driver (examples/analysis/customer_v2.py) imports only stdlib +
httpx. Every customer action below goes through it over real HTTP; privileged
setup and worker execution stay in tests/support/v2_customer_http_harness.py.

Declaration sourcing rule: customer-side declarations (reconstruction wires,
selectors, evidence intents) are built in this test from public customer GET
responses (registration context epoch, returned submission refs) plus explicit
known synthetic metadata. Direct store reads happen only in named operator
preparation (policy/context issuance, sealed-subject resolution) and post-hoc
assertions, never as customer input.

Generated-data/software labelling: the 2x2 GeoTIFF and CSV bytes are synthetic
in-test fixtures with known heights. They exercise the real Core
ingress/inspection/measurement HTTP contracts but never prove customer
export, field accuracy, or operational containment. Inspection and checkpoint
measurement run the real byte entrypoints behind production admission gates,
but execution is software-only (no Docker containment, systemd, or deployed
service proof), and the generated bytes never prove field truth. Runtime
identity digests used by the test worker are simulated local builds, not
deployed-executable proof.
"""

