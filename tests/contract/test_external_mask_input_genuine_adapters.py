"""Genuine Core-backed V3 masked path: real stores, real bytes, real keys.

Synthetic bytes only (small generated GeoTIFFs, never field/customer data).
Every authority mechanism is the real Core lane:

- reconstruction: real ``ExternalReconstructionStore`` register + seal with a
  real filesystem observation port serving the generated DSM bytes;
- inspection: real ``ExternalArtifactInspectionStore`` issue + claim + report
  with real lease fences; report measurements are read from the real
  generated bytes with rasterio (test-observed grid facts, labelled as such —
  not a certified inspector run);
- DSM-lane validation policy: real registry + ACTIVE policy; the policy
  authority double below is test-only for the DSM lane (mirroring the repo's
  own fixture pattern) and is never used for the mask lane;
- WorkArea/AP/evidence/validation: real stores, shared coordinator; the AP
  assessment reaches ADMIT_PROVISIONAL with empty evidence (no terminal
  facts), so no V2 numeric result is ever required or created;
- mask inspection: the real contained primitive
  (``inspect_mask_bytes_v1``) with the bounded binary-mask parser;
- activation: fresh Ed25519 keys minted in the test's private directory and
  a real purpose-separated activation (``MASKED_ANALYSIS_V3``) verified by
  the real loader on every check — explicitly not production authority;
- journals replayed across a simulated restart at the end.

``test_genuine_v2_unavailable_cell_masked`` proves the V2-numeric gap with
real bytes: the current DSM carries a NaN cell inside the masked region, so
a full-zone V2 100% common-valid rule would fail while the masked effective
zone stays fully valid.  No V2 execution store is ever instantiated.
"""

