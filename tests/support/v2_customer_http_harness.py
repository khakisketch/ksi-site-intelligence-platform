    # -- servers ------------------------------------------------------
    def start_servers(self) -> None:
        harness = self
        storage = self._storage()

        class ObjectHandler(BaseHTTPRequestHandler):
            def _key(self) -> str | None:
                if not self.path.startswith("/objects/"):
                    return None
                return unquote(self.path.removeprefix("/objects/"))

            def do_PUT(self) -> None:  # noqa: N802
                import hashlib as _hashlib

                key = self._key()
                if key is None:
                    self.send_error(404)
                    return
                if self.headers.get("Authorization"):
                    harness.object_put_auth_hits.append(key)
                    self.send_error(403)
                    return
                try:
                    length = int(self.headers.get("Content-Length", "0"))
                except ValueError:
                    self.send_error(411)
                    return
                payload = self.rfile.read(length)
                presented = self.headers.get("x-amz-checksum-sha256")
                observed = "sha256:" + _hashlib.sha256(payload).hexdigest()
                if presented is None or presented != observed:
                    # Enforce the grant's digest binding instead of a permissive PUT.
                    self.send_error(400)
                    return
                storage.put_bytes(
                    key,
                    payload,
                    content_type=self.headers.get("Content-Type", "application/octet-stream"),
                )
                self.send_response(200)
                self.send_header("Content-Length", "0")
                self.end_headers()

            def do_GET(self) -> None:  # noqa: N802
                key = self._key()
                if key is None:
                    self.send_error(404)
                    return
                try:
                    payload = storage.object_bytes(key)
                except KeyError:
                    self.send_error(404)
                    return
                self.send_response(200)
                self.send_header("Content-Type", "application/octet-stream")
                self.send_header("Content-Length", str(len(payload)))
                self.end_headers()
                self.wfile.write(payload)

            def log_message(self, _format: str, *_args: object) -> None:
                return

        object_server = ThreadingHTTPServer(("127.0.0.1", 0), ObjectHandler)
        object_thread = Thread(target=object_server.serve_forever, daemon=True)
        object_thread.start()
        self.object_origin = f"http://127.0.0.1:{object_server.server_port}"
        storage.set_loopback_origin(self.object_origin)

        listen_socket = socket.socket()
        listen_socket.bind(("127.0.0.1", 0))
        listen_socket.listen(128)
        self.core_origin = f"http://127.0.0.1:{listen_socket.getsockname()[1]}"
        server = uvicorn.Server(uvicorn.Config(self._app, log_level="warning", access_log=False))
        core_thread = Thread(target=lambda: server.run(sockets=[listen_socket]), daemon=True)
        core_thread.start()
        for _ in range(150):
            if server.started:
                break
            assert core_thread.is_alive(), "local Core server stopped during startup"
            time.sleep(0.02)
        assert server.started
        self._servers = [object_server, object_thread, server, core_thread, listen_socket]

    def stop_servers(self) -> None:
        if not self._servers:
            return
        object_server, object_thread, server, core_thread, listen_socket = self._servers
        server.should_exit = True
        core_thread.join(timeout=10)
        listen_socket.close()
        object_server.shutdown()
        object_server.server_close()
        object_thread.join(timeout=10)
        self._servers = []
        self.core_origin = ""
        self.object_origin = ""

