"""Test-only harness for the customer HTTP-only E2E (C3/C4).

Trusted test setup only: assembles a real Core app from the retained exact
policy/context authorities, registers one Site/WorkArea as the operator
precondition, installs a real signed FIELD_OPERATOR OIDC mapping, and serves
Core (uvicorn) plus a PUT-capable object server over real loopback sockets.

The customer driver under test (examples/analysis/customer_v2.py) performs
every customer action over HTTP with httpx; this harness never acts as the
customer. Operator/worker steps (policy admission, inspection execution,
evidence-context issuance, numeric worker runs) are explicit separate methods
so the test can label them as operator actions, not consumer behavior.

Inspection and measurement run the REAL byte entrypoints over UDS. Every
launch is gated by production admission functions against test-generated
Ed25519-signed manifests (re-signed bodies, never the fake ``b'x'*64``
signature): the inspector UDS server enforces signature verification +
execution binding + grammar/parser/envelope/ceiling checks per launch, and the
measurement UDS server enforces production ``admit_measurement_manifest`` per
launch. No gate is disabled or bypassed; a rejected launch never yields an
outcome. This is still software-only execution (no Docker containment,
systemd, or deployed service), and generated bytes never prove customer
export, field accuracy, or operational containment.
"""

